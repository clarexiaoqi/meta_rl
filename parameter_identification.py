def relative_error_percent(
    estimate: float,
    reference: float,
) -> float:
    """
    Return absolute relative error as a percentage.
    """

    estimate = float(estimate)
    reference = float(reference)

    if reference == 0.0:
        return np.nan

    return (
        abs(
            estimate
            - reference
        )
        / abs(reference)
        * 100.0
    )


