def maximum_finite_absolute_value(
    values: pd.Series,
) -> float:
    """
    Return the maximum absolute finite value in a Series.
    """

    numeric_values = pd.to_numeric(
        values,
        errors="coerce",
    ).to_numpy(
        dtype=np.float64
    )

    finite_values = numeric_values[
        np.isfinite(
            numeric_values
        )
    ]

    if finite_values.size == 0:
        return np.nan

    return float(
        np.max(
            np.abs(
                finite_values
            )
        )
    )


def run_true_parameter_reproduction_check(
    true_parameter_values: Sequence[float],
    dataset: pd.DataFrame,
    rmse_tolerance: float,
    controller_tolerance: float,
    output_directory: Path,
    allow_failed_check: bool,
) -> Dict[str, object]:
    """
    Confirm that the identification model reproduces the environment.

    Optimization should not begin unless the true parameters reproduce
    both temperature states to approximately numerical precision.
    """

    true_evaluation = (
        evaluate_parameter_set(
            parameter_values=(
                true_parameter_values
            ),
            dataset=dataset,
        )
    )

    one_step_predictions = (
        true_evaluation[
            "one_step_predictions"
        ]
    )

    one_step_metrics = (
        true_evaluation[
            "one_step_metrics"
        ]
    )

    rollout_metrics = (
        true_evaluation[
            "rollout_metrics"
        ]
    )

    controller_diagnostics = (
        calculate_controller_state_errors(
            predictions=(
                one_step_predictions
            ),
            dataset=dataset,
        )
    )

    controller_error_columns = [
        column_name
        for column_name in (
            "integral_error_end_error",
            "prev_zat_sp_end_error",
            "damper_signal_end_error",
            "m_fan_end_error",
        )
        if column_name
        in controller_diagnostics.columns
    ]

    maximum_controller_errors = {}

    for column_name in controller_error_columns:
        maximum_controller_errors[
            column_name
        ] = (
            maximum_finite_absolute_value(
                controller_diagnostics[
                    column_name
                ]
            )
        )

    finite_controller_errors = [
        value
        for value in (
            maximum_controller_errors
            .values()
        )
        if np.isfinite(value)
    ]

    maximum_controller_error = (
        max(finite_controller_errors)
        if finite_controller_errors
        else np.nan
    )

    temperature_check_passed = (
        one_step_metrics.combined_rmse
        <= rmse_tolerance
    )

    controller_check_passed = (
        not finite_controller_errors
        or maximum_controller_error
        <= controller_tolerance
    )

    full_check_passed = (
        temperature_check_passed
        and controller_check_passed
    )

    reproduction_directory = (
        output_directory
        / "true_parameter_reproduction"
    )

    reproduction_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    controller_diagnostics.to_csv(
        reproduction_directory
        / "true_parameters_one_step_diagnostics.csv",
        index=False,
    )

    true_evaluation[
        "rollout_predictions"
    ].to_csv(
        reproduction_directory
        / "true_parameters_rollout_diagnostics.csv",
        index=False,
    )

    reproduction_summary = pd.DataFrame(
        [
            {
                "one_step_envelope_rmse":
                    one_step_metrics
                    .envelope_rmse,
                "one_step_zone_rmse":
                    one_step_metrics
                    .zone_rmse,
                "one_step_combined_rmse":
                    one_step_metrics
                    .combined_rmse,
                "rollout_envelope_rmse":
                    rollout_metrics
                    .envelope_rmse,
                "rollout_zone_rmse":
                    rollout_metrics
                    .zone_rmse,
                "rollout_combined_rmse":
                    rollout_metrics
                    .combined_rmse,
                "temperature_rmse_tolerance":
                    float(
                        rmse_tolerance
                    ),
                "controller_tolerance":
                    float(
                        controller_tolerance
                    ),
                "maximum_controller_error":
                    float(
                        maximum_controller_error
                    )
                    if np.isfinite(
                        maximum_controller_error
                    )
                    else np.nan,
                "temperature_check_passed":
                    bool(
                        temperature_check_passed
                    ),
                "controller_check_passed":
                    bool(
                        controller_check_passed
                    ),
                "full_check_passed":
                    bool(
                        full_check_passed
                    ),
            }
        ]
    )

    reproduction_summary.to_csv(
        reproduction_directory
        / "true_parameter_reproduction_summary.csv",
        index=False,
    )

    print("=" * 78)
    print("TRUE-PARAMETER MODEL-REPRODUCTION CHECK")
    print("=" * 78)

    print(
        f"One-step envelope RMSE: "
        f"{one_step_metrics.envelope_rmse:.12g} °C"
    )

    print(
        f"One-step zone RMSE:     "
        f"{one_step_metrics.zone_rmse:.12g} °C"
    )

    print(
        f"One-step combined RMSE: "
        f"{one_step_metrics.combined_rmse:.12g} °C"
    )

    print()

    print(
        f"Rollout envelope RMSE:  "
        f"{rollout_metrics.envelope_rmse:.12g} °C"
    )

    print(
        f"Rollout zone RMSE:      "
        f"{rollout_metrics.zone_rmse:.12g} °C"
    )

    print(
        f"Rollout combined RMSE:  "
        f"{rollout_metrics.combined_rmse:.12g} °C"
    )

    if finite_controller_errors:
        print()

        print(
            "Maximum controller-state errors:"
        )

        for (
            column_name,
            maximum_error,
        ) in maximum_controller_errors.items():
            print(
                f"  {column_name:<32} "
                f"{maximum_error:.12g}"
            )

    print()

    if full_check_passed:
        print(
            "PASS: The exact identification model "
            "reproduces the true environment."
        )

    else:
        print(
            "FAIL: The true parameters do not reproduce "
            "the collected transitions within tolerance."
        )

        print(
            "Do not trust parameter-optimization results "
            "until this mismatch is resolved."
        )

    print("=" * 78)
    print()

    if (
        not full_check_passed
        and not allow_failed_check
    ):
        raise RuntimeError(
            "True-parameter reproduction check failed. "
            "Optimization was stopped. Inspect:\n"
            f"{reproduction_directory}"
        )

    return {
        "evaluation":
            true_evaluation,
        "controller_diagnostics":
            controller_diagnostics,
        "summary":
            reproduction_summary,
        "temperature_check_passed":
            temperature_check_passed,
        "controller_check_passed":
            controller_check_passed,
        "full_check_passed":
            full_check_passed,
    }


