def bounds_to_arrays(
    bounds: Mapping[str, Tuple[float, float]],
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Convert parameter-bound dictionaries to lower and upper arrays.
    """

    lower_values: List[float] = []
    upper_values: List[float] = []

    for parameter_name in PARAMETER_NAMES:
        if parameter_name not in bounds:
            raise KeyError(
                f"Missing bounds for parameter "
                f"{parameter_name}."
            )

        lower_bound, upper_bound = bounds[
            parameter_name
        ]

        lower_bound = float(lower_bound)
        upper_bound = float(upper_bound)

        if not np.isfinite(lower_bound):
            raise ValueError(
                f"Lower bound for {parameter_name} "
                "must be finite."
            )

        if not np.isfinite(upper_bound):
            raise ValueError(
                f"Upper bound for {parameter_name} "
                "must be finite."
            )

        if lower_bound <= 0.0:
            raise ValueError(
                f"Lower bound for {parameter_name} "
                "must be positive."
            )

        if lower_bound >= upper_bound:
            raise ValueError(
                f"Lower bound must be smaller than the "
                f"upper bound for {parameter_name}."
            )

        lower_values.append(lower_bound)
        upper_values.append(upper_bound)

    return (
        np.asarray(
            lower_values,
            dtype=np.float64,
        ),
        np.asarray(
            upper_values,
            dtype=np.float64,
        ),
    )


def verify_initial_guess_inside_bounds(
    initial_guess: np.ndarray,
    lower_bounds: np.ndarray,
    upper_bounds: np.ndarray,
) -> None:
    """
    Ensure that the generic initial guess lies inside all bounds.
    """

    below_lower_bound = (
        initial_guess < lower_bounds
    )

    above_upper_bound = (
        initial_guess > upper_bounds
    )

    if (
        np.any(below_lower_bound)
        or np.any(above_upper_bound)
    ):
        invalid_parameter_names = [
            PARAMETER_NAMES[index]
            for index in range(
                len(PARAMETER_NAMES)
            )
            if (
                below_lower_bound[index]
                or above_upper_bound[index]
            )
        ]

        raise ValueError(
            "Initial generic parameters are outside "
            "the configured bounds for: "
            + ", ".join(
                invalid_parameter_names
            )
        )


