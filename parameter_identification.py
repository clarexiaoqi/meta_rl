def evaluate_parameter_set(
    parameter_values: Sequence[float],
    dataset: pd.DataFrame,
) -> Dict[str, object]:
    """
    Evaluate a parameter set in one-step and rollout modes.
    """

    parameters = (
        ThreeRTwoCParameters
        .from_array(
            parameter_values
        )
    )

    one_step_predictions = (
        simulate_one_step_predictions(
            parameters=parameters,
            dataset=dataset,
        )
    )

    rollout_predictions = (
        simulate_rollout(
            parameters=parameters,
            dataset=dataset,
        )
    )

    one_step_metrics = (
        calculate_simulation_metrics(
            one_step_predictions
        )
    )

    rollout_metrics = (
        calculate_simulation_metrics(
            rollout_predictions
        )
    )

    return {
        "parameters":
            parameters.to_dict(),
        "one_step_predictions":
            one_step_predictions,
        "rollout_predictions":
            rollout_predictions,
        "one_step_metrics":
            one_step_metrics,
        "rollout_metrics":
            rollout_metrics,
    }


