def build_parameter_comparison_table(
    true_parameters: Mapping[str, float],
    generic_parameters: Mapping[str, float],
    identified_parameters: Mapping[str, float],
    parameter_bounds: Mapping[
        str,
        Tuple[float, float],
    ],
) -> pd.DataFrame:
    """
    Build the true/generic/identified parameter comparison table.
    """

    rows = []

    for parameter_name in PARAMETER_NAMES:
        true_value = float(
            true_parameters[
                parameter_name
            ]
        )

        generic_value = float(
            generic_parameters[
                parameter_name
            ]
        )

        identified_value = float(
            identified_parameters[
                parameter_name
            ]
        )

        lower_bound, upper_bound = (
            parameter_bounds[
                parameter_name
            ]
        )

        generic_relative_error = (
            relative_error_percent(
                estimate=generic_value,
                reference=true_value,
            )
        )

        identified_relative_error = (
            relative_error_percent(
                estimate=identified_value,
                reference=true_value,
            )
        )

        rows.append(
            {
                "parameter":
                    parameter_name,
                "true_value":
                    true_value,
                "generic_value":
                    generic_value,
                "identified_value":
                    identified_value,
                "lower_bound":
                    float(lower_bound),
                "upper_bound":
                    float(upper_bound),
                "generic_relative_error_percent":
                    generic_relative_error,
                "identified_relative_error_percent":
                    identified_relative_error,
                "error_improvement_percent_points":
                    (
                        generic_relative_error
                        - identified_relative_error
                    ),
                "identified_at_lower_bound":
                    bool(
                        np.isclose(
                            identified_value,
                            lower_bound,
                            rtol=1.0e-5,
                            atol=1.0e-12,
                        )
                    ),
                "identified_at_upper_bound":
                    bool(
                        np.isclose(
                            identified_value,
                            upper_bound,
                            rtol=1.0e-5,
                            atol=1.0e-12,
                        )
                    ),
            }
        )

    return pd.DataFrame(
        rows
    )


def build_metrics_table(
    generic_evaluation: Dict[str, object],
    identified_evaluation: Dict[str, object],
    true_evaluation: Dict[str, object],
) -> pd.DataFrame:
    """
    Build generic, identified, and true-model metrics.
    """

    rows = []

    evaluations = {
        "generic":
            generic_evaluation,
        "identified":
            identified_evaluation,
        "true":
            true_evaluation,
    }

    for (
        parameter_source,
        evaluation,
    ) in evaluations.items():
        for prediction_mode in (
            "one_step",
            "rollout",
        ):
            metrics = evaluation[
                f"{prediction_mode}_metrics"
            ]

            rows.append(
                {
                    "parameter_source":
                        parameter_source,
                    "prediction_mode":
                        prediction_mode,
                    **metrics.to_dict(),
                }
            )

    return pd.DataFrame(
        rows
    )


def save_parameter_json(
    output_file: Path,
    parameters: Mapping[str, float],
) -> None:
    """
    Save identified parameters in JSON format.
    """

    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    serializable_parameters = {
        parameter_name: float(
            parameters[
                parameter_name
            ]
        )
        for parameter_name in PARAMETER_NAMES
    }

    with output_file.open(
        "w",
        encoding="utf-8",
    ) as output_stream:
        json.dump(
            serializable_parameters,
            output_stream,
            indent=4,
        )


