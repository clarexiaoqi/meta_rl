"""
parameter_identification.py

Estimate 3R2C building parameters from exact environment-transition data.

Required files
--------------
1. parameter_config.py
2. parameter_identification_model.py
3. results/identification/identification_data.csv

Parameter order
---------------
    [C_env, C_air, R_rc, R_oe, R_er]

Identification procedure
------------------------
1. Load the transition dataset generated by the updated
   collect_identification_data.py.

2. Verify that the exact identification model reproduces the dataset
   when the true parameters are used.

3. Evaluate the generic parameter values.

4. Start bounded nonlinear least-squares optimization from the generic
   parameter values.

5. Evaluate and save results for:
   - generic parameters
   - identified parameters
   - true parameters

Important
---------
The identification model now exactly reconstructs:

- the continuous 3R2C matrices;
- the 300-second zero-order-hold discretization;
- the six internal PI-controller loops;
- airflow and supply-air heat transfer;
- terminal reheat;
- the 30% / 70% solar-gain split.

No reconstructed Q_HVAC_total_est_W input is used.

TRUE_PARAMS are used only for model-reproduction checks and final
accuracy evaluation. They are not supplied to the optimizer.
"""

