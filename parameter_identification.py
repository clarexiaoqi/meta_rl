class IdentificationObjective:
    """
    Callable least-squares objective with evaluation tracking.

    SciPy's least_squares does not expose an iteration callback in all
    supported SciPy versions. Therefore, this class records every
    objective-function call.

    The resulting CSV is an objective-evaluation history, not a strict
    optimizer-iteration history.
    """

    def __init__(
        self,
        dataset: pd.DataFrame,
        prediction_mode: str,
        envelope_weight: float,
        zone_weight: float,
        print_every: int = 10,
    ) -> None:
        self.dataset = dataset
        self.prediction_mode = (
            prediction_mode
        )

        self.envelope_weight = float(
            envelope_weight
        )

        self.zone_weight = float(
            zone_weight
        )

        self.print_every = int(
            print_every
        )

        self.evaluation_count = 0

        self.history: List[
            Dict[str, float]
        ] = []

        self.best_mse = np.inf

        self.best_parameters: (
            np.ndarray | None
        ) = None

    def __call__(
        self,
        parameter_values: np.ndarray,
    ) -> np.ndarray:
        """
        Evaluate the weighted temperature residual vector.
        """

        self.evaluation_count += 1

        try:
            residuals = compute_residual_vector(
                parameters=parameter_values,
                dataset=self.dataset,
                envelope_weight=(
                    self.envelope_weight
                ),
                zone_weight=(
                    self.zone_weight
                ),
                simulation_mode=(
                    self.prediction_mode
                ),
                normalize_by_samples=False,
            )

        except Exception as error:
            print(
                f"[ERROR] Objective evaluation "
                f"{self.evaluation_count} failed."
            )

            print(
                "Parameter values:"
            )

            for parameter_name, value in zip(
                PARAMETER_NAMES,
                parameter_values,
            ):
                print(
                    f"  {parameter_name}: "
                    f"{float(value):.12g}"
                )

            raise RuntimeError(
                "Parameter-identification objective "
                "evaluation failed."
            ) from error

        mean_squared_error = float(
            np.mean(
                residuals ** 2
            )
        )

        root_mean_squared_error = float(
            np.sqrt(
                mean_squared_error
            )
        )

        least_squares_cost = float(
            0.5
            * np.sum(
                residuals ** 2
            )
        )

        if mean_squared_error < self.best_mse:
            self.best_mse = (
                mean_squared_error
            )

            self.best_parameters = (
                np.asarray(
                    parameter_values,
                    dtype=np.float64,
                ).copy()
            )

        history_row: Dict[str, float] = {
            "evaluation": float(
                self.evaluation_count
            ),
            "weighted_mse":
                mean_squared_error,
            "weighted_rmse":
                root_mean_squared_error,
            "least_squares_cost":
                least_squares_cost,
            "best_weighted_mse_so_far":
                float(self.best_mse),
            "best_weighted_rmse_so_far":
                float(
                    np.sqrt(
                        self.best_mse
                    )
                ),
        }

        for parameter_index, parameter_name in enumerate(
            PARAMETER_NAMES
        ):
            history_row[
                parameter_name
            ] = float(
                parameter_values[
                    parameter_index
                ]
            )

        self.history.append(
            history_row
        )

        should_print = (
            self.print_every > 0
            and (
                self.evaluation_count == 1
                or self.evaluation_count
                % self.print_every
                == 0
            )
        )

        if should_print:
            print(
                f"Objective evaluation "
                f"{self.evaluation_count:4d} | "
                f"weighted RMSE = "
                f"{root_mean_squared_error:.12g} °C | "
                f"best = "
                f"{np.sqrt(self.best_mse):.12g} °C"
            )

        return residuals


